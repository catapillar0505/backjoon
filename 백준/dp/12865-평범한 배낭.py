n, k = map(int, input().split()) # 물건의 개수와 배낭이 감당가능한 무게

items = [tuple(map(int,input().split())) for _ in range(n)]

# dp[i][w] = i번째 물품까지 고려했을 때, 무게 w에서의 최대 가치
# w는 배낭의 크기가 변하는 마법의 배낭이라고 생각했을때 배낭의 사이즈 1~7
dp = [[0] * (k + 1) for _ in range(n + 1)]
    
for i in range(1, n + 1): # i란 몇번째 물건인지
    weight, value = items[i-1] # 현재 물건의 무게와 가치
    for w in range(k + 1): # w란 배낭이 감당가능한 무게
        if weight <= w: # => 배낭에 현재 물건을 담을수 있는 경우 (왜냐하면 배낭의 수용가능무게보다 현재 물건의 무게가 같거나 작아서)
            dp[i][w] = max(dp[i-1][w], dp[i-1][w-weight] + value) # 배낭이 감당 가능한 무게가 w인 , 현재 물건 제외 이전 물건까지 포함한 상태의 배낭에서의, 최대 가치 vs  이전 물건 포함 상태에서[i-1], 현재 배낭에서 현재 물건을 빼고 남은 무게 만큼에[w-weight], 가능한 물건의 최대 가치 +현재 물건의 가치 => 둘중에 더 큰값
        else: # => 배낭에 현재 물건을 못담는 경우 (배낭의 수용가능무게보다 현재 물건의 무게가 커서) 
            dp[i][w] = dp[i-1][w] # 현재 물건 제외, 이전 물건까지 고려했을 상황 기준으로, 배낭의 감당가능한 무게가 w인 배낭에 들어갈 수 있는, 물건의 최대 가치

print(dp[n][k])


