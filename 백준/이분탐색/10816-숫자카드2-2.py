# ================================
# 문제 유형 분석 (예제 1번 기준)
# ================================
# 백준 10816번: 숫자 카드 2
#
# 첫 번째 예제 입력:
#   10
#   6 3 2 10 10 10 -10 -10 7 3
#   8
#   10 9 -5 2 3 4 5 -10
#
# 입력 의미:
#   - N = 10 (상근이가 가진 카드 개수)
#   - 카드들: [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#   - M = 8 (확인할 숫자 개수)
#   - 확인할 숫자들: [10, 9, -5, 2, 3, 4, 5, -10]
#
# 문제 목표:
#   각 확인할 숫자가 상근이 카드에 몇 개 있는지 세기
#
# 예제 시뮬레이션 (Counter 방법):
#   Counter는 리스트의 각 원소 개수를 자동으로 세어주는 도구입니다.
#
#   카드 리스트: [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#   Counter 적용 후:
#     Counter({10: 3, 3: 2, -10: 2, 6: 1, 2: 1, 7: 1})
#     의미: 10이 3개, 3이 2개, -10이 2개, 6이 1개, 2가 1개, 7이 1개
#
#   각 쿼리 처리:
#     10 -> counter[10] = 3
#     9 -> counter[9] = 0 (없으면 0 반환)
#     -5 -> counter[-5] = 0
#     2 -> counter[2] = 1
#     3 -> counter[3] = 2
#     4 -> counter[4] = 0
#     5 -> counter[5] = 0
#     -10 -> counter[-10] = 2
#
# 예상 출력: 3 0 0 1 2 0 0 2
#
# 해결 방법:
#   - Counter로 각 카드의 개수를 한 번에 세기
#   - 각 쿼리마다 Counter에서 개수 조회 (O(1))
#
# 시간복잡도: O(N + M)
#   - Counter 생성: O(N)
#   - M번 조회: O(M)
#   - 가장 빠른 방법!

# ================================
# 코드 분석 (예제 데이터 추적)
# ================================

import sys
from collections import Counter

# Counter는 파이썬 collections 모듈의 클래스입니다.
# 리스트나 반복 가능한 객체의 각 원소 개수를 자동으로 세어줍니다.
# 딕셔너리를 상속받아 만들어졌으며, 없는 키는 0을 반환합니다.

# 1. 입력을 빠르게 받기 위한 설정
input = sys.stdin.readline
# 이제 input()을 호출하면 sys.stdin.readline()이 실행됩니다.
# 이는 여러 줄을 입력받을 때 훨씬 빠릅니다.

# 2. 카드 개수 입력
n = int(input().strip())
# 예제: n = 10
# strip()은 끝의 공백과 줄바꿈 제거

# 3. 카드들을 입력받아 Counter로 개수 세기
cards = list(map(int, input().split()))
# 예제: input().split() = ['6', '3', '2', '10', '10', '10', '-10', '-10', '7', '3']
#       map(int, ...) = [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#       cards = [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]

counter = Counter(cards)
# Counter가 cards 리스트를 분석해서 각 숫자의 개수를 셉니다.
#
# 예제에서 Counter가 어떻게 만들어지는지:
# cards = [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#
# Counter가 리스트를 순회하며 개수를 셉니다:
# 6: 1번 나옴
# 3: 2번 나옴 (2번째, 10번째)
# 2: 1번 나옴
# 10: 3번 나옴 (4번째, 5번째, 6번째)
# -10: 2번 나옴 (7번째, 8번째)
# 7: 1번 나옴
#
# 결과: Counter({10: 3, 3: 2, -10: 2, 6: 1, 2: 1, 7: 1})
# Counter는 딕셔너리처럼 {숫자: 개수} 형태로 저장합니다.
# 가장 많이 나온 것부터 보여주는 특징이 있습니다.

# 4. 찾을 카드 개수 입력
m = int(input().strip())
# 예제: m = 8

# 5. 찾을 카드들을 리스트로 입력
his_cards = list(map(int, input().split()))
# 예제: his_cards = [10, 9, -5, 2, 3, 4, 5, -10]

# 6. 결과를 저장할 리스트
res = []

# 7. 각 쿼리에 대해 Counter에서 개수 찾기
for c in his_cards:
    # Counter는 딕셔너리를 상속받았으므로 counter[c]로 개수를 조회
    # 만약 c가 없으면 자동으로 0을 반환합니다 (KeyError가 안 남!)
    count = counter[c]
    res.append(str(count))

# 예제에서 각 쿼리가 어떻게 처리되는지 추적:
# counter = Counter({10: 3, 3: 2, -10: 2, 6: 1, 2: 1, 7: 1})
#
# c = 10:
#   counter[10] = 3  (10이 3개 있음)
#   res = ['3']
#
# c = 9:
#   counter[9] = 0  (9가 없으므로 0 반환, KeyError 안 남!)
#   res = ['3', '0']
#
# c = -5:
#   counter[-5] = 0  (-5가 없으므로 0 반환)
#   res = ['3', '0', '0']
#
# c = 2:
#   counter[2] = 1  (2가 1개 있음)
#   res = ['3', '0', '0', '1']
#
# c = 3:
#   counter[3] = 2  (3이 2개 있음)
#   res = ['3', '0', '0', '1', '2']
#
# c = 4:
#   counter[4] = 0  (4가 없으므로 0 반환)
#   res = ['3', '0', '0', '1', '2', '0']
#
# c = 5:
#   counter[5] = 0  (5가 없으므로 0 반환)
#   res = ['3', '0', '0', '1', '2', '0', '0']
#
# c = -10:
#   counter[-10] = 2  (-10이 2개 있음)
#   res = ['3', '0', '0', '1', '2', '0', '0', '2']

# 8. 결과 출력 (공백으로 구분)
print(' '.join(res))
# join은 리스트의 문자열들을 공백으로 연결합니다.
# ['3', '0', '0', '1', '2', '0', '0', '2'] -> "3 0 0 1 2 0 0 2"

# ================================
# Q&A (예제 중심 질문)
# ================================

# Q1: Counter란 무엇인가요?
# A1: Python collections 모듈의 클래스로, 리스트의 각 원소 개수를 자동으로 세어줍니다.
#     딕셔너리를 상속받았으며, 없는 키를 조회하면 KeyError 대신 0을 반환합니다.
#     예제: Counter([1, 1, 2, 3, 3, 3]) = Counter({3: 3, 1: 2, 2: 1})

# Q2: 예제에서 Counter는 어떻게 생성되나요?
# A2: cards = [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#     Counter(cards)는 각 숫자가 몇 번 나오는지 세어줍니다.
#     결과: Counter({10: 3, 3: 2, -10: 2, 6: 1, 2: 1, 7: 1})
#     가장 많이 나온 10부터 보여줍니다.

# Q3: counter[9]가 0을 반환하는 이유는?
# A3: Counter는 없는 키를 조회하면 KeyError를 발생시키지 않고 0을 반환합니다.
#     이는 Counter가 defaultdict(int)처럼 동작하기 때문입니다.
#     따라서 counter[9]는 0을 반환합니다.

# Q4: Counter를 사용하는 것과 딕셔너리를 직접 만드는 것의 차이는?
# A4: Counter:
#       - 한 줄로 생성: Counter(cards)
#       - 없는 키는 자동으로 0 반환
#       - most_common() 같은 편리한 메서드 제공
#     딕셔너리:
#       - 반복문으로 직접 세어야 함
#       - 없는 키는 get(key, 0)으로 처리해야 함
#     Counter가 더 간결하고 편리합니다!

# Q5: 예제에서 10의 개수는 어떻게 3이 되나요?
# A5: cards = [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#                     ^4  ^5  ^6
#     인덱스 3, 4, 5 위치에 10이 세 번 나타나므로
#     Counter({10: 3, ...})가 됩니다.

# Q6: str(count)를 하는 이유는?
# A6: print()에서 ' '.join()을 사용하려면 리스트의 모든 원소가 문자열이어야 합니다.
#     counter[c]는 정수를 반환하므로 str()로 문자열로 변환합니다.
#     예: 3 -> '3', 0 -> '0'

# Q7: 이 방법의 시간복잡도는?
# A7: 1) Counter 생성: O(N) - N개 카드를 한 번 순회
#     2) M번 조회: O(M) - 각 조회는 O(1)
#     총합: O(N + M)
#     이분 탐색 O(N log N + M log N)보다 빠릅니다!

# Q8: Counter는 정렬이 필요한가요?
# A8: 아니요! Counter는 정렬 없이 바로 개수를 셉니다.
#     이분 탐색은 정렬이 필수지만, Counter는 해시 테이블 방식이라 정렬 불필요합니다.
#     예제: [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]를 그대로 사용

# Q9: Counter의 내부 구조는 어떻게 되나요?
# A9: Counter는 딕셔너리를 상속받아 만들어졌습니다.
#     내부적으로 해시 테이블을 사용하여 각 원소를 키로, 개수를 값으로 저장합니다.
#     따라서 조회가 O(1)로 매우 빠릅니다.

# Q10: 예제에서 3의 개수는 어떻게 2가 되나요?
# A10: cards = [6, 3, 2, 10, 10, 10, -10, -10, 7, 3]
#                  ^2                             ^10
#     인덱스 1과 9 위치에 3이 두 번 나타나므로
#     counter[3] = 2가 됩니다.

# Q11: Counter의 다른 유용한 기능은?
# A11: 1) most_common(n): 가장 많이 나온 n개 반환
#        예: counter.most_common(3) = [(10, 3), (3, 2), (-10, 2)]
#     2) elements(): 개수만큼 반복되는 원소들 반환
#        예: list(counter.elements()) = [6, 3, 3, 2, 10, 10, 10, ...]
#     3) 덧셈, 뺄셈 가능
#        예: Counter([1,2]) + Counter([2,3]) = Counter({2: 2, 1: 1, 3: 1})

# Q12: 백준에서 이 방법이 통과되나요?
# A12: 네! Counter는 매우 빠르고 효율적입니다.
#      N과 M이 최대 500,000이어도 O(N + M) = 1,000,000 정도로 충분히 빠릅니다.
#      실제로 이분 탐색보다 더 빠른 경우가 많습니다.
