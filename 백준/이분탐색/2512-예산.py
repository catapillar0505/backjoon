# Q&A (예제 중심 질문)
# ================================

# Q1: 왜 이 문제는 lower_bound/upper_bound를 사용하지 않나요?
# A1: 이 문제는 "개수 세기"가 아니라 "최적값 찾기" 문제입니다.
#     10816번은 "2가 몇 개?"를 찾지만,
#     2512번은 "조건을 만족하는 최대 상한액?"을 찾습니다.
#     따라서 일반 이분탐색 하나만 사용합니다.

# Q2: 예제에서 왜 127이 답인가요?
# A2: 상한액 127일 때:
#       120 + 110 + 127 + 127 = 484 (485 이하, 가능!)
#     상한액 128일 때:
#       120 + 110 + 128 + 128 = 486 (485 초과, 불가능!)
#     따라서 가능한 최대 상한액은 127입니다.

# Q3: start와 end의 초기값을 왜 0과 max(lst)로 설정하나요?
# A3: 상한액의 범위는 최소 0, 최대 가장 큰 예산 요청액입니다.
#     상한액이 max(lst)보다 크면 의미가 없습니다.
#     (모든 요청을 그대로 배정하는 것과 같음)
#     예제: 0 ~ 150

# Q4: total == M일 때 왜 바로 출력하나요?
# A4: 상한액을 올리면 total이 증가하거나 유지됩니다 (절대 감소 안 함).
#     total == M이면 딱 맞는 거고, 더 올리면 M을 초과합니다.
#     따라서 더 탐색할 필요 없이 바로 그게 최대 상한액입니다!
#
#     예: total = 485, M = 485 (딱 맞음!)
#         상한액을 1이라도 올리면 total > 485가 됩니다.
#         따라서 현재 상한액이 최대!
#
# Q4-1: result = mid를 하는 이유는?
# A4-1: total < M이면 mid는 "가능한 답"입니다.
#       하지만 더 큰 값도 가능할 수 있으므로 계속 탐색합니다.
#       나중에 더 큰 값을 찾지 못하면 이 값이 최종 답이 됩니다.

# Q5: 예제에서 상한액 113일 때는 어떻게 되나요?
# A5: lst = [120, 110, 140, 150], 상한액 = 113
#     120 > 113 -> 113 배정
#     110 <= 113 -> 110 배정
#     140 > 113 -> 113 배정
#     150 > 113 -> 113 배정
#     총합: 113 + 110 + 113 + 113 = 449
#     449 <= 485이므로 가능! 하지만 127이 더 큰 답입니다.

# Q6: 이분 탐색이 끝나는 조건은?
# A6: start > end가 되면 종료합니다.
#     예제: 마지막에 start=128, end=127이 되어 종료
#     이때 result에 저장된 127이 최종 답입니다.

# Q7: 만약 모든 요청을 그대로 배정할 수 있다면?
# A7: 예를 들어 lst=[10, 20, 30], M=100이면:
#     모든 요청 합 = 60 <= 100
#     이 경우 상한액은 max(lst) = 30이 됩니다.
#     30 이상으로 상한액을 올려도 의미가 없습니다.

# Q8: 왜 start = mid + 1이고 end = mid - 1인가요?
# A8: mid는 이미 확인했으므로 다음 범위에서 제외합니다.
#     total <= M: mid는 가능하므로 더 큰 값 찾기 (mid+1 ~ end)
#     total > M: mid는 불가능하므로 더 작은 값 찾기 (start ~ mid-1)

# Q9: 예제에서 몇 번 반복하나요?
# A9: 7번 반복합니다.
#     범위가 0~150(151개)에서 시작해서
#     log2(151) = 약 7.2번 정도 반복합니다.
#     이분 탐색은 O(log N)으로 매우 빠릅니다!

# Q10: 이 알고리즘의 시간복잡도는?
# A10: 1) 이분 탐색 반복: O(log(max(lst)))
#      2) 각 반복마다 N개 예산 합 계산: O(N)
#      총합: O(N * log(max(lst)))
#      예제: 4 * log(150) = 4 * 7.2 = 약 29번 연산

# Q11: 10816번과 2512번의 핵심 차이는?
# A11: 10816번: "2가 몇 개?" (개수 세기)
#        -> lower_bound와 upper_bound로 "범위" 찾기
#        -> 범위의 차이 = 개수
#      2512번: "최대 상한액은?" (최적값 찾기)
#        -> 일반 이분탐색으로 "값" 찾기
#        -> 조건을 만족하는 최대값 찾기

# Q12: total == M인 경우 예제를 보여주세요!
# A12: lst = [10, 20, 30, 40], M = 80
#      1회전: mid=20, total=10+20+20+20=70 < 80, result=20, start=21
#      2회전: mid=30, total=10+20+30+30=90 > 80, end=29
#      3회전: mid=25, total=10+20+25+25=80 == 80 -> 바로 출력 25!
#      딱 맞으므로 더 탐색할 필요 없이 즉시 종료!
#
# Q13: 원래 예제에서는 왜 total == M이 안 나왔나요?
# A13: lst = [120, 110, 140, 150], M = 485
#      상한액 127: total = 484 (< 485)
#      상한액 128: total = 486 (> 485)
#      485를 정확히 만드는 상한액이 없습니다. (정수로는)
#      따라서 total < M인 값 중 최대인 127이 답입니다.
