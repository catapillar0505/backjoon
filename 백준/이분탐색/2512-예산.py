# -*- coding: utf-8 -*-

# ================================
# 문제 유형 분석 (예제 1번 기준)
# ================================
# 백준 2512번: 예산
#
# 첫 번째 예제 입력:
#   4
#   120 110 140 150
#   485
#
# 입력 의미:
#   - N = 4 (지방의 수)
#   - 예산 요청: [120, 110, 140, 150]
#   - M = 485 (총 예산)
#
# 문제 목표:
#   모든 요청이 배정될 수 있는 최대 상한액 찾기
#
# 예제 시뮬레이션 (이분 탐색으로 최적값 찾기):
#   상한액 개념:
#     - 상한액보다 작은 요청: 요청액 그대로 배정
#     - 상한액보다 큰 요청: 상한액만큼 배정
#
#   예를 들어, 상한액 = 127일 때:
#     120 (127보다 작음) -> 120 배정
#     110 (127보다 작음) -> 110 배정
#     140 (127보다 큼) -> 127 배정
#     150 (127보다 큼) -> 127 배정
#     총합: 120 + 110 + 127 + 127 = 484 (485 이하, 가능!)
#
#   상한액 = 128일 때:
#     120 + 110 + 128 + 128 = 486 (485 초과, 불가능!)
#
#   상한액 = 126일 때:
#     120 + 110 + 126 + 126 = 482 (485 이하, 가능하지만 127보다 작음)
#
#   따라서 최대 상한액 = 127
#
# 예상 출력: 127
#
# 이분 탐색 전략:
#   - 답의 범위: 0 ~ max(예산 요청) = 0 ~ 150
#   - 상한액을 이분 탐색으로 찾기
#   - mid를 상한액으로 했을 때 총합 계산
#   - 총합 <= M: 가능 -> 더 큰 상한액 시도 (start = mid + 1)
#   - 총합 > M: 불가능 -> 더 작은 상한액 시도 (end = mid - 1)
#
# 핵심:
#   이것은 "개수 세기"가 아니라 "최적값 찾기" 문제!
#   lower_bound/upper_bound가 아니라 일반 이분탐색 사용

# ================================
# 코드 분석 (예제 데이터 추적)
# ================================

# 1. 지방의 수 입력
N = int(input())
# 예제: N = 4

# 2. 각 지방의 예산 요청 입력
lst = list(map(int, input().split()))
# 예제: lst = [120, 110, 140, 150]

# 3. 총 예산 입력
M = int(input())
# 예제: M = 485

# 4. 결과를 저장할 변수 (최대 상한액)
result = 0

# 5. 이분 탐색 범위 설정
start, end = 0, max(lst)
# 예제: start = 0, end = 150
# 상한액은 최소 0, 최대 가장 큰 예산 요청액 (150)

# 6. 이분 탐색 시작
while start <= end:
    # 중간값을 상한액 후보로 설정
    mid = (start + end) // 2
    # 예제 1회전: mid = (0 + 150) // 2 = 75

    # 7. mid를 상한액으로 했을 때 총 예산 계산
    total = 0
    for l in lst:
        if l > mid:
            # 요청액이 상한액보다 크면 상한액만 배정
            total += mid
        else:
            # 요청액이 상한액 이하면 요청액 그대로 배정
            total += l

    # 예제 1회전 (mid = 75):
    #   120 > 75 -> total += 75 (total = 75)
    #   110 > 75 -> total += 75 (total = 150)
    #   140 > 75 -> total += 75 (total = 225)
    #   150 > 75 -> total += 75 (total = 300)
    #   total = 300

    # 8. 조건에 따라 탐색 범위 조정
    if total == M:
        # 총합이 M과 딱 맞으면 최적!
        # 상한액을 더 올리면 total이 M을 초과하므로
        # 현재 mid가 최대 상한액입니다.
        print(mid)
        exit()  # 바로 종료
    elif total < M:
        # 총합이 M보다 작으면 가능!
        # 더 큰 상한액을 시도해볼 수 있음
        result = mid  # 현재 mid는 가능한 답이므로 저장
        start = mid + 1  # 더 큰 값 찾기
    else:  # total > M
        # 총합이 M을 초과하면 불가능!
        # 더 작은 상한액을 시도해야 함
        end = mid - 1

    # 예제 1회전 결과:
    #   total(300) < M(485) -> 가능!
    #   result = 75
    #   start = 76

# 9. 결과 출력
print(result)
# 예제: 127

