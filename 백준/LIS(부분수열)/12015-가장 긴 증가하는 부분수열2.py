# -*- coding: utf-8 -*-

# ================================
# 문제 유형 분석 (예제 기준)
# ================================
# 백준 12015번: 가장 긴 증가하는 부분수열 2 (LIS with Binary Search)
#
# 예제 입력:
#   6
#   10 20 10 30 20 50
#
# 입력 의미:
#   - N = 6 (수열의 크기)
#   - 수열: [10, 20, 10, 30, 20, 50]
#
# 문제 목표:
#   가장 긴 증가하는 부분수열의 길이 구하기
#   11053번과 같은 문제지만 N이 최대 1,000,000!
#   O(N^2) DP로는 시간 초과 -> O(N log N) 알고리즘 필요!
#
# 예제 시뮬레이션 (이분 탐색 방법):
#   수열: [10, 20, 10, 30, 20, 50]
#
#   핵심 아이디어:
#     LIS 배열을 유지하면서, 각 원소를 적절한 위치에 삽입/교체
#
#   단계별 과정:
#     초기: LIS = [10]
#
#     20 처리: LIS[-1]=10 < 20 -> 추가
#              LIS = [10, 20]
#
#     10 처리: LIS[-1]=20 >= 10 -> 10 이상인 첫 위치 찾기 (0번)
#              LIS[0] = 10 (교체)
#              LIS = [10, 20]
#
#     30 처리: LIS[-1]=20 < 30 -> 추가
#              LIS = [10, 20, 30]
#
#     20 처리: LIS[-1]=30 >= 20 -> 20 이상인 첫 위치 찾기 (1번)
#              LIS[1] = 20 (교체)
#              LIS = [10, 20, 30]
#
#     50 처리: LIS[-1]=30 < 50 -> 추가
#              LIS = [10, 20, 30, 50]
#
#   최종 LIS 길이: 4
#
# 중요 개념:
#   - LIS 배열은 "실제 LIS"가 아니라 "길이를 추적하는 배열"
#   - 각 위치의 값은 "그 길이의 LIS를 만들 수 있는 최소값"
#   - 이분 탐색으로 lower_bound를 찾아 교체
#
# 11053번(O(N^2))과 12015번(O(N log N)) 차이:
#   11053번: d[i] = i를 마지막으로 하는 LIS 길이 (DP 배열)
#   12015번: LIS = 현재까지의 LIS 후보 배열 (이분 탐색)
#
# 시간복잡도: O(N log N)
#   - N개 원소 각각에 대해
#   - 이분 탐색으로 위치 찾기: O(log N)
#   - 총합: O(N log N)

# ================================
# 코드 분석 (예제 데이터 추적)
# ================================

import sys
input = sys.stdin.readline

# 1. 수열의 크기 입력
N = int(input())
# 예제: N = 6

# 2. 수열 입력
A = [*map(int, input().split())]
# [*map(...)]은 list(map(...))와 동일
# 예제: A = [10, 20, 10, 30, 20, 50]

# 3. LIS 배열 초기화
LIS = [A[0]]
# 첫 번째 원소로 시작
# 예제: LIS = [10]
# LIS[i]의 의미: 길이 i+1인 증가 부분수열을 만들 수 있는 마지막 원소의 최솟값

# 4. 이분 탐색으로 위치 찾기 함수
def findPlace(e):
    # e: 삽입/교체할 원소
    # 반환: e 이상인 첫 번째 위치 (lower_bound)

    start = 0
    end = len(LIS) - 1
    # 예제: LIS = [10, 20, 30], e = 20일 때
    #       start = 0, end = 2

    while start <= end:
        mid = (start + end) // 2
        # 중간 위치 계산

        if LIS[mid] == e:
            # 정확히 같은 값을 찾으면 그 위치 반환
            return mid

        elif LIS[mid] < e:
            # LIS[mid]가 e보다 작으면 오른쪽 절반 탐색
            start = mid + 1
            # 더 큰 값을 찾아야 함

        else:  # LIS[mid] > e
            # LIS[mid]가 e보다 크면 왼쪽 절반 탐색
            end = mid - 1
            # 더 작은 인덱스에 e 이상인 값이 있을 수 있음

    # start > end가 되면 종료
    # start가 e 이상인 첫 번째 위치 (lower_bound)
    return start

# 예제에서 findPlace가 어떻게 동작하는지:
#
# LIS = [10, 20, 30], e = 20 찾기:
#   1회전: start=0, end=2, mid=1
#          LIS[1]=20 == 20 -> return 1
#
# LIS = [10, 20, 30], e = 25 찾기:
#   1회전: start=0, end=2, mid=1
#          LIS[1]=20 < 25 -> start=2
#   2회전: start=2, end=2, mid=2
#          LIS[2]=30 > 25 -> end=1
#   종료: start=2, end=1 (start > end)
#   return 2 (25 이상인 첫 위치는 인덱스 2)

# 5. 각 원소 처리
for item in A:
    # A의 모든 원소를 순서대로 처리
    # 예제: item은 차례대로 10, 20, 10, 30, 20, 50

    if LIS[-1] < item:
        # LIS의 마지막 값보다 item이 크면
        # LIS를 연장할 수 있음 -> 추가
        LIS.append(item)

        # 예제 item=20일 때:
        #   LIS = [10], LIS[-1] = 10 < 20
        #   LIS.append(20) -> LIS = [10, 20]

    else:
        # LIS[-1] >= item이면
        # item을 LIS의 적절한 위치에 교체
        idx = findPlace(item)
        # item 이상인 첫 번째 위치 찾기

        LIS[idx] = item
        # 그 위치의 값을 item으로 교체

        # 예제 item=10일 때 (두 번째 10):
        #   LIS = [10, 20], LIS[-1] = 20 >= 10
        #   idx = findPlace(10) = 0 (10 이상인 첫 위치)
        #   LIS[0] = 10 (교체, 사실 같은 값)
        #   LIS = [10, 20]

# 예제 전체 과정 추적:
#
# A = [10, 20, 10, 30, 20, 50]
#
# 초기: LIS = [10]
#
# item = 20:
#   LIS[-1]=10 < 20 -> 추가
#   LIS = [10, 20]
#
# item = 10:
#   LIS[-1]=20 >= 10 -> findPlace(10) = 0
#   LIS[0] = 10
#   LIS = [10, 20]
#   (10을 10으로 교체, 변화 없음)
#
# item = 30:
#   LIS[-1]=20 < 30 -> 추가
#   LIS = [10, 20, 30]
#
# item = 20:
#   LIS[-1]=30 >= 20 -> findPlace(20) = 1
#   LIS[1] = 20
#   LIS = [10, 20, 30]
#   (20을 20으로 교체, 변화 없음)
#
# item = 50:
#   LIS[-1]=30 < 50 -> 추가
#   LIS = [10, 20, 30, 50]
#
# 최종: LIS = [10, 20, 30, 50], len(LIS) = 4

# 6. LIS의 길이 출력
print(len(LIS))
# 예제: len([10, 20, 30, 50]) = 4
# 출력: 4

# ================================
# Q&A (예제 중심 질문)
# ================================

# Q1: 11053번과 12015번의 차이는 무엇인가요?
# A1: 11053번: O(N^2) DP, N <= 1,000
#     12015번: O(N log N) 이분 탐색, N <= 1,000,000
#     같은 문제지만 제한이 다릅니다!
#     12015번은 N이 크므로 더 빠른 알고리즘이 필요합니다.

# Q2: LIS 배열이 실제 LIS인가요?
# A2: 아닙니다! LIS 배열은 "길이 추적용" 배열입니다.
#     예제에서 최종 LIS = [10, 20, 30, 50]은 우연히 실제 LIS와 같지만,
#     항상 그런 것은 아닙니다.
#     중요한 건 LIS의 "길이"입니다!

# Q3: LIS[i]의 의미는 무엇인가요?
# A3: "길이 i+1인 증가 부분수열을 만들 수 있는 마지막 원소의 최솟값"
#     예: LIS = [10, 20, 30]
#         LIS[0]=10: 길이 1의 LIS 마지막 최솟값
#         LIS[1]=20: 길이 2의 LIS 마지막 최솟값
#         LIS[2]=30: 길이 3의 LIS 마지막 최솟값

# Q4: 왜 교체를 하나요?
# A4: 더 작은 값으로 교체하면 나중에 더 긴 LIS를 만들 수 있습니다.
#     예: A = [3, 1, 5]
#         3 처리: LIS = [3]
#         1 처리: LIS[0] = 1로 교체 -> LIS = [1]
#                 (1이 3보다 작으므로 나중에 더 유리)
#         5 처리: LIS = [1, 5]
#     만약 교체 안 하면: [3] -> [3] -> [3, 5] (길이 2)
#     교체하면: [3] -> [1] -> [1, 5] (길이 2, 같음)
#     하지만 복잡한 경우엔 교체가 더 유리합니다!

# Q5: findPlace는 lower_bound인가요?
# A5: 네! findPlace(e)는 e 이상인 첫 번째 위치를 찾습니다.
#     이것이 정확히 lower_bound입니다.
#     예: LIS = [10, 20, 30]
#         findPlace(15) = 1 (15 이상인 첫 위치는 20)
#         findPlace(20) = 1 (20 이상인 첫 위치는 20)
#         findPlace(25) = 2 (25 이상인 첫 위치는 30)

# Q6: 예제에서 두 번째 10을 처리할 때 왜 교체하나요?
# A6: LIS = [10, 20], item = 10
#     findPlace(10) = 0 (10 이상인 첫 위치)
#     LIS[0] = 10 (10을 10으로 교체)
#     실제로는 변화가 없지만, 알고리즘상 교체합니다.
#     이미 10이 있으므로 의미는 없지만 일관성을 위해!

# Q7: 예제에서 두 번째 20을 처리할 때는?
# A7: LIS = [10, 20, 30], item = 20
#     LIS[-1]=30 >= 20이므로 교체 필요
#     findPlace(20) = 1 (20 이상인 첫 위치)
#     LIS[1] = 20 (20을 20으로 교체)
#     역시 변화 없음!

# Q8: 다른 예제로 확인해볼까요?
# A8: A = [3, 5, 7, 9, 2, 1, 4, 8]
#     초기: LIS = [3]
#     5: LIS = [3, 5]
#     7: LIS = [3, 5, 7]
#     9: LIS = [3, 5, 7, 9]
#     2: findPlace(2) = 0, LIS = [2, 5, 7, 9]
#     1: findPlace(1) = 0, LIS = [1, 5, 7, 9]
#     4: findPlace(4) = 1, LIS = [1, 4, 7, 9]
#     8: findPlace(8) = 3, LIS = [1, 4, 7, 8]
#     답: 4
#     실제 LIS는 [3, 5, 7, 8] 또는 [3, 5, 7, 9] 등

# Q9: LIS가 실제 LIS와 다른 예시는?
# A9: 위 Q8 예제에서 최종 LIS = [1, 4, 7, 8]
#     하지만 실제 LIS는 [3, 5, 7, 8] 또는 [3, 5, 7, 9]
#     [1, 4, 7, 8]은 실제로는 불가능! (1 다음에 4, 7, 8은 안 나옴)
#     하지만 길이는 정확히 4입니다!

# Q10: 시간복잡도가 왜 O(N log N)인가요?
# A10: N개 원소 각각에 대해:
#      - LIS[-1]과 비교: O(1)
#      - findPlace (이분 탐색): O(log N)
#      총합: O(N) * O(log N) = O(N log N)
#      예제: N=1,000,000이면 약 20,000,000번 연산

# Q11: 왜 LIS를 첫 원소로 초기화하나요?
# A11: 빈 배열로 시작하면 첫 원소 처리 시 특별한 경우 처리 필요
#      첫 원소로 초기화하면 코드가 간단해집니다.
#      A[0]은 항상 길이 1의 LIS이므로 안전!

# Q12: start <= end인 이유는?
# A12: lower_bound를 정확히 찾기 위함입니다.
#      start == end일 때도 확인해야 정확한 위치를 찾습니다.
#      최종적으로 start가 e 이상인 첫 위치가 됩니다.

# Q13: Python의 bisect를 사용해도 되나요?
# A13: 네! bisect.bisect_left를 사용하면 더 간단합니다.
#      from bisect import bisect_left
#      idx = bisect_left(LIS, item)
#      하지만 직접 구현하면 이분 탐색 원리를 더 잘 이해할 수 있습니다!

# Q14: 11053번과 답이 같나요?
# A14: 네, 같은 문제이므로 답은 같습니다!
#      차이는 시간복잡도와 입력 크기 제한뿐입니다.
#      예제: [10, 20, 10, 30, 20, 50]
#      11053번(O(N^2)): 4
#      12015번(O(N log N)): 4

# Q15: 이 알고리즘의 핵심은?
# A15: "작은 값으로 교체하면 나중에 더 긴 LIS를 만들 가능성이 높다"
#      LIS 배열의 각 위치는 "그 길이의 LIS를 만들 수 있는 최소 마지막 값"을 유지
#      이분 탐색으로 빠르게 위치를 찾아 교체
#      결과적으로 O(N log N)에 LIS 길이를 구할 수 있습니다!

# Q16: 실제 LIS를 출력하려면?
# A16: 추가 정보를 저장해야 합니다.
#      각 원소마다 이전 원소의 인덱스를 기록하고
#      역추적(backtracking)으로 실제 수열을 구성합니다.
#      이 코드는 길이만 구하므로 추가 구현이 필요합니다.
