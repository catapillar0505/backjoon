# -*- coding: utf-8 -*-

# ================================
# 문제 유형 분석 (예제 기준)
# ================================
# 백준 11053번: 가장 긴 증가하는 부분수열 (LIS - Longest Increasing Subsequence)
#
# 예제 입력:
#   6
#   10 20 10 30 20 50
#
# 입력 의미:
#   - N = 6 (수열의 크기)
#   - 수열: [10, 20, 10, 30, 20, 50]
#
# 문제 목표:
#   가장 긴 증가하는 부분수열의 길이 구하기
#   - 부분수열: 원래 수열에서 일부를 선택한 것 (순서는 유지)
#   - 증가하는: 선택한 수들이 점점 커지는 것
#
# 예제 시뮬레이션:
#   수열: [10, 20, 10, 30, 20, 50]
#         인덱스: 0   1   2   3   4   5
#
#   가능한 증가하는 부분수열:
#     [10] -> 길이 1
#     [10, 20] -> 길이 2
#     [10, 20, 30] -> 길이 3
#     [10, 20, 30, 50] -> 길이 4 (최대!)
#     [10, 20, 50] -> 길이 3
#     [10, 30, 50] -> 길이 3
#     [20, 30, 50] -> 길이 3
#
#   정답: 4 (10 -> 20 -> 30 -> 50)
#
# 핵심 아이디어 (동적 계획법 - DP):
#   d[i] = i번째 원소를 마지막으로 하는 가장 긴 증가하는 부분수열의 길이
#
#   점화식:
#     d[i] = max(d[j] + 1) (단, j < i이고 arr[j] < arr[i])
#     의미: i보다 앞에 있고(j < i), 값이 작은(arr[j] < arr[i]) 모든 j에 대해
#           d[j] + 1의 최댓값이 d[i]
#
# 예제로 DP 테이블 만들기:
#   arr:  [10, 20, 10, 30, 20, 50]
#   인덱스: 0   1   2   3   4   5
#
#   d[0] = 1 (10만 선택)
#   d[1] = 2 (10 -> 20)
#   d[2] = 1 (10만 선택)
#   d[3] = 3 (10 -> 20 -> 30)
#   d[4] = 2 (10 -> 20)
#   d[5] = 4 (10 -> 20 -> 30 -> 50)
#
#   최댓값: max(d) = 4

# ================================
# 코드 분석 (예제 데이터 추적)
# ================================

# 1. 수열의 크기 입력
n = int(input())
# 예제: n = 6

# 2. 수열 입력
arr = list(map(int, input().split()))
# 예제: arr = [10, 20, 10, 30, 20, 50]
#       인덱스:  0   1   2   3   4   5

# 3. DP 테이블 초기화
# i번째 원소를 마지막으로 하는 가장 긴 증가하는 부분수열의 길이를 저장
d = [1] * n
# 모든 원소를 1로 초기화하는 이유:
#   - 어떤 원소든 혼자만 선택하면 길이가 1
#   - 예제: d = [1, 1, 1, 1, 1, 1]

# 4. DP 테이블 채우기
for i in range(1, n):  # 1번째 인덱스부터 n-1번째 인덱스까지
    # i번째 원소를 마지막으로 하는 가장 긴 증가하는 부분수열 찾기

    # 예제 i=1 (arr[1]=20):
    #   arr[1]=20을 마지막으로 하는 가장 긴 증가 부분수열은?

    for j in range(i):  # i보다 작은 모든 j에 대해
        # j는 i 이전의 모든 인덱스 (0부터 i-1까지)

        if arr[j] < arr[i]:  # j의 값이 i의 값보다 작으면 (증가 조건)
            # arr[j] 다음에 arr[i]를 붙일 수 있음!
            # d[j] + 1: j를 마지막으로 하는 길이에 i를 추가
            d[i] = max(d[i], d[j] + 1)
            # 여러 j 중에서 가장 긴 것을 선택

# 예제에서 DP 테이블이 어떻게 채워지는지 추적:
#
# 초기: d = [1, 1, 1, 1, 1, 1]
#       arr = [10, 20, 10, 30, 20, 50]
#
# i=1 (arr[1]=20):
#   j=0: arr[0]=10 < arr[1]=20 -> d[1] = max(1, d[0]+1) = max(1, 2) = 2
#   결과: d = [1, 2, 1, 1, 1, 1]
#   의미: 10 -> 20 (길이 2)
#
# i=2 (arr[2]=10):
#   j=0: arr[0]=10 < arr[2]=10 -> 거짓 (10 < 10은 거짓)
#   j=1: arr[1]=20 < arr[2]=10 -> 거짓
#   결과: d = [1, 2, 1, 1, 1, 1] (변화 없음)
#   의미: 10만 선택 (길이 1)
#
# i=3 (arr[3]=30):
#   j=0: arr[0]=10 < arr[3]=30 -> d[3] = max(1, d[0]+1) = max(1, 2) = 2
#   j=1: arr[1]=20 < arr[3]=30 -> d[3] = max(2, d[1]+1) = max(2, 3) = 3
#   j=2: arr[2]=10 < arr[3]=30 -> d[3] = max(3, d[2]+1) = max(3, 2) = 3
#   결과: d = [1, 2, 1, 3, 1, 1]
#   의미: 10 -> 20 -> 30 (길이 3)
#
# i=4 (arr[4]=20):
#   j=0: arr[0]=10 < arr[4]=20 -> d[4] = max(1, d[0]+1) = max(1, 2) = 2
#   j=1: arr[1]=20 < arr[4]=20 -> 거짓 (20 < 20은 거짓)
#   j=2: arr[2]=10 < arr[4]=20 -> d[4] = max(2, d[2]+1) = max(2, 2) = 2
#   j=3: arr[3]=30 < arr[4]=20 -> 거짓
#   결과: d = [1, 2, 1, 3, 2, 1]
#   의미: 10 -> 20 (길이 2)
#
# i=5 (arr[5]=50):
#   j=0: arr[0]=10 < arr[5]=50 -> d[5] = max(1, d[0]+1) = max(1, 2) = 2
#   j=1: arr[1]=20 < arr[5]=50 -> d[5] = max(2, d[1]+1) = max(2, 3) = 3
#   j=2: arr[2]=10 < arr[5]=50 -> d[5] = max(3, d[2]+1) = max(3, 2) = 3
#   j=3: arr[3]=30 < arr[5]=50 -> d[5] = max(3, d[3]+1) = max(3, 4) = 4
#   j=4: arr[4]=20 < arr[5]=50 -> d[5] = max(4, d[4]+1) = max(4, 3) = 4
#   결과: d = [1, 2, 1, 3, 2, 4]
#   의미: 10 -> 20 -> 30 -> 50 (길이 4)
#
# 최종 DP 테이블: d = [1, 2, 1, 3, 2, 4]

# 5. 가장 긴 증가하는 부분수열의 길이 출력
print(max(d))
# max(d) = max([1, 2, 1, 3, 2, 4]) = 4
# 예제 출력: 4

# ================================
# Q&A (예제 중심 질문)
# ================================

# Q1: 부분수열이란 무엇인가요?
# A1: 원래 수열에서 일부를 선택한 것으로, 순서는 유지해야 합니다.
#     예제: arr = [10, 20, 10, 30, 20, 50]
#           [10, 20, 30, 50]은 부분수열 O (순서 유지)
#           [50, 30, 20, 10]은 부분수열 X (순서 뒤집힘)
#           [10, 30, 20]은 부분수열 O (순서 유지)

# Q2: 왜 d를 전부 1로 초기화하나요?
# A2: 모든 원소는 혼자만 선택해도 길이 1의 증가하는 부분수열이 되기 때문입니다.
#     예: arr[0]=10만 선택 -> [10] (길이 1)
#         arr[3]=30만 선택 -> [30] (길이 1)
#     최소 길이는 항상 1이므로 1로 초기화!

# Q3: 예제에서 d[3] = 3이 되는 과정은?
# A3: arr[3] = 30을 마지막으로 하는 가장 긴 증가 부분수열을 찾습니다.
#     j=0: arr[0]=10 < 30, d[0]=1 -> d[3] = 1 + 1 = 2
#     j=1: arr[1]=20 < 30, d[1]=2 -> d[3] = 2 + 1 = 3
#     j=2: arr[2]=10 < 30, d[2]=1 -> d[3]는 3 유지
#     최종: d[3] = 3 (경로: 10 -> 20 -> 30)

# Q4: 점화식 d[i] = max(d[j] + 1)의 의미는?
# A4: i번째 원소를 마지막으로 추가할 때,
#     i 이전의 모든 j 중에서
#     arr[j] < arr[i]를 만족하는 j의 d[j] + 1 중 최댓값을 선택합니다.
#     의미: j를 마지막으로 하는 가장 긴 수열에 i를 추가!

# Q5: 예제에서 d[2] = 1인 이유는?
# A5: arr[2] = 10을 마지막으로 하는 증가 부분수열을 찾으면:
#     j=0: arr[0]=10 < arr[2]=10 -> 거짓 (10은 10보다 작지 않음)
#     j=1: arr[1]=20 < arr[2]=10 -> 거짓 (20은 10보다 작지 않음)
#     아무것도 선택할 수 없으므로 d[2] = 1 (10 혼자만)

# Q6: 왜 arr[j] < arr[i] 조건이 필요한가요?
# A6: "증가하는" 부분수열이므로 작은 수 다음에 큰 수가 와야 합니다.
#     arr[j] < arr[i]여야 arr[j] 다음에 arr[i]를 붙일 수 있습니다.
#     예: arr[1]=20, arr[3]=30
#         20 < 30이므로 20 다음에 30을 붙여 [20, 30] 가능

# Q7: 예제에서 최종 답이 4가 나오는 경로는?
# A7: d[5] = 4가 최댓값입니다.
#     arr[5]=50을 마지막으로 하는 가장 긴 증가 부분수열:
#       인덱스: 0 -> 1 -> 3 -> 5
#       값: 10 -> 20 -> 30 -> 50
#     길이: 4

# Q8: 시간복잡도는 어떻게 되나요?
# A8: 이중 반복문을 사용합니다.
#     외부 for문: O(N) (i는 1부터 n-1까지)
#     내부 for문: O(N) (j는 0부터 i-1까지, 평균 N/2)
#     총합: O(N^2)
#     예제: N=6이면 약 36번 연산

# Q9: 다른 예제로 확인해볼까요?
# A9: arr = [1, 3, 2, 4]
#     d[0] = 1 (1)
#     d[1] = 2 (1 -> 3)
#     d[2] = 2 (1 -> 2)
#     d[3] = 3 (1 -> 2 -> 4 또는 1 -> 3 -> 4)
#     답: max(d) = 3

# Q10: 왜 i는 1부터 시작하나요?
# A10: d[0]은 이미 1로 초기화되어 있고, 더 계산할 필요가 없습니다.
#      (0번째 원소 앞에는 아무것도 없으므로 d[0] = 1 확정)
#      따라서 i는 1부터 n-1까지만 계산합니다.

# Q11: max(d[i], d[j] + 1)에서 max를 사용하는 이유는?
# A11: 여러 j 중에서 가장 긴 것을 선택하기 위함입니다.
#      예: i=5일 때
#          j=1에서 d[5] = 3
#          j=3에서 d[5] = 4
#      max를 사용해야 4를 유지할 수 있습니다!

# Q12: 실제 수열을 출력하려면?
# A12: 이 코드는 길이만 구합니다.
#      실제 수열을 구하려면 역추적(backtracking)이 필요합니다.
#      d[i]와 함께 이전 인덱스도 저장해야 합니다.

# Q13: 같은 값이 있으면 어떻게 되나요?
# A13: 예: arr = [1, 2, 2, 3]
#      arr[j] < arr[i] 조건 때문에 같은 값은 연결되지 않습니다.
#      d[0] = 1 (1)
#      d[1] = 2 (1 -> 2)
#      d[2] = 2 (1 -> 2, arr[1]=2는 arr[2]=2보다 작지 않음)
#      d[3] = 3 (1 -> 2 -> 3)

# Q14: 예제에서 d[4] = 2인 이유는?
# A14: arr[4] = 20을 마지막으로 하는 증가 부분수열:
#      j=0: arr[0]=10 < 20 -> d[4] = 2 (10 -> 20)
#      j=1: arr[1]=20 < 20 -> 거짓 (같으므로)
#      j=2: arr[2]=10 < 20 -> d[4] = 2 (10 -> 20)
#      j=3: arr[3]=30 < 20 -> 거짓 (30 > 20)
#      최종: d[4] = 2

# Q15: DP를 사용하는 이유는?
# A15: 모든 가능한 부분수열을 다 확인하면 2^N개 (지수 시간)
#      DP를 사용하면 O(N^2)으로 빠르게 해결 가능!
#      예: N=20일 때
#          완전탐색: 2^20 = 1,048,576번
#          DP: 20^2 = 400번
